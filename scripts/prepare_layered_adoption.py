"""Copy original PNG bytes, inspect alpha, and author display-only sockets. No pixel edits."""
from pathlib import Path
import json, hashlib, shutil, copy
from PIL import Image
ROOT = Path(__file__).resolve().parents[1]
RAW = ROOT/'assets/raw/layered_actor_adoption_20261106'
ART = ROOT/'game/art/characters/layered_actor_adoption_20261106'
OUT = ROOT/'game/build/layered_actor_adoption_20261106/evidence'
SRC = Path('C:/Users/rajqiu/.codex/generated_images/01a162c1-af5d-7ce0-9577-cdddb7ad269b')
FILES = {'walk_mid_rejected':'80e0b39a-14b0-4315-a871-2461eb7d2f63','walk_mid_clean':'96f4367a-dc3a-487b-af3c-f930fb73e906','walk_down_mid':'8ed46a57-35b1-4d0b-be98-3e99ea73e997','walk_up_mid':'6791d5a0-73c6-4bc6-8795-a6db05e64aa8','attack_dao_rejected':'6d4767f9-4172-4874-a1f5-5c2d37452eae','attack_dao':'feecd8d8-366b-4f36-925f-6c041823e4ec','attack_dao_clean':'1cf91836-916d-45d4-a4f1-112f7e072b94'}
for d in (RAW,ART,OUT): d.mkdir(parents=True, exist_ok=True)
def sha(p): return hashlib.sha256(p.read_bytes()).hexdigest()
records=[]
for name, ident in FILES.items():
    source=SRC/f'exec-{ident}.png'; raw=RAW/f'{name}.png'
    if not raw.exists(): shutil.copyfile(source,raw)
    assert sha(raw)==sha(source)
    im=Image.open(raw).convert('RGBA'); alpha=im.getchannel('A')
    accepted=not name.endswith('rejected') and name!='attack_dao_clean'
    record=dict(name=name,source=str(source),raw=str(raw.relative_to(ROOT)),sha256=sha(raw),size=im.size,alpha=alpha.getextrema(),accepted=accepted)
    if accepted:
        assert im.size==(2048,768) and alpha.getextrema()[0]==0,record
        dest=ART/f'{name}.png'
        if not dest.exists(): shutil.copyfile(raw,dest)
        assert sha(dest)==sha(raw)
        record['runtime']=str(dest.relative_to(ROOT))
        record['bounds']=[alpha.crop((i*512,0,(i+1)*512,768)).point(lambda a:255 if a>=24 else 0).getbbox() for i in range(4)]
    records.append(record)
(RAW/'generation.json').write_text(json.dumps(records,ensure_ascii=False,indent=2),encoding='utf-8')
data=json.loads((ROOT/'game/build/layered_actor_20261106_lab/manifest.json').read_text(encoding='utf-8-sig'))
data['schema']='LAYERED_ACTOR_APPEARANCE_V1';data['status']='FORMAL_NAMED_WEAPON_DISPLAY'
data.pop('source_root',None)
for key in ('attack_down','attack_up'):
    data['clips'].pop(key)
    data['textures'].remove(key)
data['textures']={n:f'res://art/characters/layered_actor_20261106/{n}.png' for n in data['textures']}
for r in records:
    if r['accepted']: data['textures'][r['name']]='res://art/characters/layered_actor_adoption_20261106/'+r['name']+'.png'
for clip in data['clips'].values():
    for i,p in enumerate(clip['frames']): p['texture']=clip['texture'];p['cell_index']=i
def pose(hand,foot,angle,z,index,texture):
    return dict(hand_center=hand,grip=[hand[0]+7,hand[1]-14],foot=foot,angle=angle,weapon_z=z,cell_index=index,texture=texture,anchor_semantics='thumb_index_web_below_guard',weapon_grips={'seven_star_sword':[512,1120],'jinhe_duanyue_blade':[512,1045]})
for clip,hands,foot,angle,z in [('walk',[[378,352],[375,347],[365,363],[375,349]],[256,726],20,3),('walk_down',[[170,377],[169,377],[164,377],[171,377]],[256,737],0,3),('walk_up',[[394,395],[363,316],[368,332],[365,310]],[256,732],0,0)]:
    old=data['clips'][clip]['frames']; frames=[]
    for i in range(4):
        frames.append(old[i]); p=pose(hands[i],foot,angle,z,i,'walk_mid_clean' if clip=='walk' else clip+'_mid')
        if z==0: p['grip']=[hands[i][0]-5,hands[i][1]-10]
        frames.append(p)
    data['clips'][clip]['frames']=frames
data['clips']['attack_dao']=dict(texture='attack_dao',cell=[512,768],seconds=.22,loop=False,frames=[pose(h,[256,725],a,3,i,'attack_dao') for i,(h,a) in enumerate(zip([[165,224],[235,78],[456,462],[418,525]],[-35,-25,125,130]))])
for clip_id, angle in [('idle_down',-18),('walk_down',-18),('idle_up',22),('walk_up',22)]:
    for p in data['clips'][clip_id]['frames']:
        p['angle']=angle
data['coverage']['attack']=['right','left_mirrored']
data['limitations']=['Left mirrors right.','Only seven_star_sword and jinhe_duanyue_blade adopt this display. Other weapons retain existing sprites.','Battle hit/defeat use side poses. Existing gameplay timing and geometry remain authoritative.']
data['sha256']={n:sha(ROOT/'game'/p.removeprefix('res://')) for n,p in data['textures'].items()}
manifest=json.dumps(data,ensure_ascii=False,indent=2)
(ART/'appearance.json').write_text(manifest,encoding='utf-8')
# GDScript is included by Godot exports even when non-resource JSON is filtered.
(ART/'appearance_data.gd').write_text('# Generated by scripts/prepare_layered_adoption.py.\nconst DATA = '+manifest+'\n',encoding='utf-8')
protected=['game/project.godot','game/scripts/field/player.gd','game/scripts/battle/battle_actor.gd','game/scripts/battle/battle_controller.gd','game/scripts/autoload/inventory.gd','game/scripts/autoload/scene_router.gd']
baseline=OUT/'source_before.json'
if not baseline.exists():
    baseline.write_text(json.dumps({p:sha(ROOT/p) for p in protected},indent=2),encoding='utf-8')
    shutil.copyfile(ROOT/'game/project.godot',OUT/'project.before.godot.txt')
print(json.dumps(records,ensure_ascii=False,indent=2))
